begin;

-- ---------- MASTER TABLES ----------

create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  name varchar(80) not null,
  price integer not null default 0 check (price >= 0),
  period varchar(30) not null default 'monthly',
  ai_daily_limit integer not null default 30,
  tutor_sessions integer not null default 0 check (tutor_sessions >= 0),
  badge varchar(80),
  features jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name varchar(120) not null,
  username varchar(50) not null unique,
  email varchar(255) not null unique,
  whatsapp varchar(30),
  password varchar(255) not null,
  role varchar(20) not null default 'student'
    check (role in ('student', 'tutor', 'admin')),
  admin_type varchar(30),
  package_id bigint references public.packages(id) on delete set null,
  package_expires timestamptz,
  is_trial boolean not null default false,
  xp integer not null default 0 check (xp >= 0),
  points integer not null default 0 check (points >= 0),
  streak integer not null default 0 check (streak >= 0),
  avatar text not null default '/ma.png',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  title varchar(160) not null,
  level varchar(50) not null,
  description text,
  tutor_id bigint references public.users(id) on delete set null,
  thumbnail text,
  total_lessons integer not null default 0 check (total_lessons >= 0),
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title varchar(160) not null,
  order_index integer not null,
  video_url text,
  reading_content text,
  target_vocabulary jsonb not null default '[]'::jsonb,
  speaking_prompt text,
  xp_reward integer not null default 50 check (xp_reward between 0 and 1000),
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_id, order_index)
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array'),
  correct_answer integer not null check (correct_answer >= 0),
  xp_reward integer not null default 20 check (xp_reward between 0 and 1000),
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_progress (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed boolean not null default false,
  score integer not null default 0 check (score between 0 and 100),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, lesson_id)
);

create table if not exists public.exercises (
  id bigint generated by default as identity primary key,
  level varchar(20) not null,
  title varchar(160) not null,
  instruction text not null,
  reference_text text not null,
  translation text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.modules (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  type varchar(60) not null default 'PDF Document',
  file_size varchar(30),
  badge varchar(80) default 'Official Modul',
  description text,
  file_url text not null,
  storage_path text,
  is_published boolean not null default true,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.recorded_videos (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  tutor varchar(120),
  duration varchar(40),
  level varchar(50) not null default 'All Levels',
  video_url text not null,
  thumbnail text,
  is_published boolean not null default true,
  created_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.placement_test_leads (
  id bigint generated by default as identity primary key,
  nama varchar(120) not null,
  no_wa varchar(30) not null,
  email varchar(255),
  level_target varchar(30),
  recommended_level varchar(30),
  jadwal_trial timestamptz,
  catatan text,
  status varchar(40) not null default 'Belum Dihubungi',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  package_id bigint not null references public.packages(id) on delete restrict,
  amount integer not null check (amount >= 0),
  payment_method varchar(50) not null default 'QRIS',
  status varchar(30) not null default 'pending'
    check (status in ('pending', 'paid', 'failed', 'expired', 'refunded', 'success')),
  external_reference varchar(150) unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ai_chats (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  role varchar(20) not null check (role in ('user', 'assistant', 'system')),
  mode varchar(50) not null default 'general',
  content text not null,
  created_at timestamptz not null default now()
);

