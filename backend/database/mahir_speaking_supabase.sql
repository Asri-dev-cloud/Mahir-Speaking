-- ---------- AUTOMATIC updated_at ----------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'packages','users','courses','lessons','quizzes','user_progress',
    'exercises','modules','recorded_videos','placement_test_leads','purchases'
  ] loop
    execute format('drop trigger if exists trg_%I_updated_at on public.%I', table_name, table_name);
    execute format(
      'create trigger trg_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name, table_name
    );
  end loop;
end $$;

-- ---------- SAFE XP TRANSACTION ----------
-- Signature tetap cocok dengan backend lama. Nilai XP dari client diabaikan;
-- hadiah diambil dari lessons.xp_reward agar user tidak bisa memalsukan XP.

create or replace function public.complete_lesson_secure(
  p_user_id bigint,
  p_lesson_id bigint,
  p_score integer,
  p_xp_reward integer default null
)
returns table (
  progress_id bigint,
  new_xp integer,
  new_points integer,
  new_streak integer,
  status_code varchar
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_progress_id bigint;
  v_completed boolean;
  v_old_score integer;
  v_reward integer;
  v_xp integer;
  v_points integer;
  v_streak integer;
begin
  if not exists (select 1 from public.users where id = p_user_id) then
    return query select 0::bigint, 0, 0, 0, 'USER_NOT_FOUND'::varchar;
    return;
  end if;

  select xp_reward into v_reward
  from public.lessons
  where id = p_lesson_id;

  if v_reward is null then
    v_reward := coalesce(p_xp_reward, 80);
    -- Insert dynamic placeholder lesson to satisfy foreign key constraints
    insert into public.lessons (id, course_id, title, order_index, reading_content, target_vocabulary, speaking_prompt, xp_reward, is_published)
    values (p_lesson_id, 1, 'Unit ' || p_lesson_id || ' Speaking Practice', p_lesson_id, 'Dynamic Reading Content', '[]'::jsonb, 'Dynamic Speaking Prompt', v_reward, true)
    on conflict (id) do nothing;
  end if;

  select id, completed, score
    into v_progress_id, v_completed, v_old_score
  from public.user_progress
  where user_id = p_user_id and lesson_id = p_lesson_id
  for update;

  if coalesce(v_completed, false) then
    update public.user_progress
       set score = greatest(v_old_score, greatest(0, least(100, p_score)))
     where id = v_progress_id;

    select xp, points, streak into v_xp, v_points, v_streak
    from public.users where id = p_user_id;

    return query select v_progress_id, v_xp, v_points, v_streak, 'ALREADY_COMPLETED'::varchar;
    return;
  end if;

  insert into public.user_progress
    (user_id, lesson_id, completed, score, completed_at)
  values
    (p_user_id, p_lesson_id, true, greatest(0, least(100, p_score)), now())
  on conflict (user_id, lesson_id) do update
    set completed = true,
        score = greatest(public.user_progress.score, excluded.score),
        completed_at = now()
  returning id into v_progress_id;

  update public.users
     set xp = xp + v_reward,
         points = points + floor(v_reward / 2.0)::integer,
         streak = streak + 1
    where id = p_user_id
  returning xp, points, streak into v_xp, v_points, v_streak;

  return query select v_progress_id, v_xp, v_points, v_streak, 'SUCCESS'::varchar;
end;
$$;

-- ---------- USEFUL VIEWS ----------

create or replace view public.user_progress_detail as
select
  up.id,
  up.user_id,
  u.full_name,
  u.username,
  up.lesson_id,
  l.title as lesson_title,
  c.title as course_title,
  up.completed,
  up.score,
  up.completed_at
from public.user_progress up
join public.users u on u.id = up.user_id
join public.lessons l on l.id = up.lesson_id
join public.courses c on c.id = l.course_id;

create or replace view public.leaderboard_view as
select
  row_number() over (order by u.xp desc, u.points desc, u.created_at asc) as rank,
  u.id,
  u.full_name,
  u.username,
  u.avatar,
  u.xp,
  u.points,
  u.streak,
  p.name as package_name,
  p.badge as package_badge
from public.users u
left join public.packages p on p.id = u.package_id
where u.role = 'student';

